// Regenerates assets/js/modules.js from the files in assets/js/dists/ and assets/js/relations/.
// Run after adding a module:  node tools/update-manifest.mjs
// (The site only requests modules listed in the manifest, so a missing page never causes a 404.)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const list = dir => fs.readdirSync(path.join(ROOT, dir)).filter(f => f.endsWith('.js')).map(f => f.slice(0, -3)).sort();
export function manifestSource() {
  const d = list('assets/js/dists'), r = list('assets/js/relations');
  return `// AUTO-GENERATED by tools/update-manifest.mjs — lists the modules that exist so pages never request a missing file.
// Run \`node tools/update-manifest.mjs\` after adding a file to assets/js/dists/ or assets/js/relations/.
export const DIST_MODULES = ${JSON.stringify(d, null, 2)};
export const RELATION_MODULES = ${JSON.stringify(r, null, 2)};
`;
}
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  fs.writeFileSync(path.join(ROOT, 'assets/js/modules.js'), manifestSource());
  console.log('wrote assets/js/modules.js');
}
